"""ELT task definitions and loaders.

An ELT task has two halves that must never be mixed:

* the *project base* (``input_dir``) that is copied into the agent's workspace:
  ``config.yaml``, ``data_model.yaml``, ``schemas/``, docs, source files, ...
* the *grader assets* that stay on the host: expected raw-table row counts
  (stage 1), ground-truth CSVs and sort keys for each data model (stage 2).

Two loaders are provided: ``load_local_tasks`` for the self-contained tasks
under ``tasks/`` (used by the credential-free tests), and
``load_eltbench_tasks`` for official ELT-Bench input bundles produced by
``setup/write_config.py`` plus the evaluation metadata and ground truth.
"""

from __future__ import annotations

import json
import shutil
from dataclasses import dataclass, field
from pathlib import Path

# Never copied into a workspace: host-side credentials and grader material.
WORKSPACE_EXCLUDE_GLOBS = ("*_credential.json", "_grader*", "gt_*")


@dataclass(frozen=True)
class ELTTask:
    """One ELT pipeline to build."""

    name: str
    input_dir: Path
    expected_rows: dict[str, int]
    gt_dir: Path
    sort_keys: dict[str, list[str]] = field(default_factory=dict)
    # "local" tasks use the in-workspace loader tools; "eltbench" tasks use
    # Airbyte + Terraform + dbt inside the official ELT-Bench container.
    kind: str = "local"

    @property
    def model_names(self) -> list[str]:
        return sorted(p.stem for p in self.gt_dir.glob("*.csv"))


def _read_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def load_local_tasks(root: str | Path = "tasks", only: list[str] | None = None) -> list[ELTTask]:
    """Load tasks laid out as ``<root>/<name>/{workspace,grader}``."""
    root = Path(root)
    tasks: list[ELTTask] = []
    for task_dir in sorted(p for p in root.iterdir() if p.is_dir()):
        if only and task_dir.name not in only:
            continue
        grader = task_dir / "grader"
        tasks.append(
            ELTTask(
                name=task_dir.name,
                input_dir=task_dir / "workspace",
                expected_rows=_read_json(grader / "table.json"),
                gt_dir=grader / "gt",
                sort_keys=_read_json(grader / "sort_key.json"),
                kind="local",
            )
        )
    return tasks


def load_eltbench_tasks(
    inputs_root: str | Path,
    evaluation_dir: str | Path,
    gt_root: str | Path,
    only: list[str] | None = None,
) -> list[ELTTask]:
    """Load official ELT-Bench tasks.

    Args:
        inputs_root: Directory of per-task input bundles (``ELT-Bench/inputs``,
            generated by ``setup/write_config.py --destination <warehouse>``).
        evaluation_dir: ``ELT-Bench/evaluation`` (holds ``table.json`` and
            ``sort_key.json``).
        gt_root: Ground-truth directory with one ``<task>/<model>.csv`` folder
            per task (e.g. ``gt_snowflake`` from the ``tttjjj/elt_bench`` dataset).
    """
    inputs_root, evaluation_dir, gt_root = Path(inputs_root), Path(evaluation_dir), Path(gt_root)
    table_json = _read_json(evaluation_dir / "table.json")
    sort_keys = _read_json(evaluation_dir / "sort_key.json")
    tasks: list[ELTTask] = []
    for task_dir in sorted(p for p in inputs_root.iterdir() if p.is_dir()):
        name = task_dir.name
        if only and name not in only:
            continue
        if name not in table_json or not (gt_root / name).is_dir():
            continue
        tasks.append(
            ELTTask(
                name=name,
                input_dir=task_dir,
                expected_rows=table_json[name],
                gt_dir=gt_root / name,
                sort_keys=sort_keys.get(name, {}),
                kind="eltbench",
            )
        )
    return tasks


def materialize_workspace(task: ELTTask, workspace: Path) -> Path:
    """Copy the task's project base into a fresh workspace directory."""
    if workspace.exists():
        shutil.rmtree(workspace)
    shutil.copytree(
        task.input_dir,
        workspace,
        ignore=shutil.ignore_patterns(*WORKSPACE_EXCLUDE_GLOBS),
    )
    return workspace
